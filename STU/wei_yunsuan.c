#include <stdio.h>

unsigned int updateBits(unsigned int a) {
    // 清除第 7-17 位（11 位）
    unsigned int mask_7_17 = (1 << 11) - 1; // 0b000000000000000000000000000011111111111
    mask_7_17 <<= 6; // 左移 6 位，变为 0b000000000000000000000011111111111000000000000000
    a &= ~mask_7_17; // 清除原始值中的第 7-17 位

    // 将 937 赋给第 7-17 位
    a |= (937 << 6); // 将 937 左移 6 位，并与 a 进行或运算

    // 清除第 21-25 位（5 位）
    unsigned int mask_21_25 = (1 << 5) - 1; // 0b00000000000000000000000000000000000000000000000000000000000011111
    mask_21_25 <<= 20; // 左移 20 位，变为 0b0000000000000000000000000000000000000000000000001111100000000000
    a &= ~mask_21_25; // 清除原始值中的第 21-25 位

    // 将 17 赋给第 21-25 位
    a |= (17 << 20); // 将 17 左移 20 位，并与 a 进行或运算

    return a;
}

int main() {
    unsigned int a = 0; // 假设 a 最初为 0
    unsigned int result = updateBits(a);
    printf("更新后的结果是: %u\n", result);
    return 0;
}
